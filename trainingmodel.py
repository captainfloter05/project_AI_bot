# Загрузка модели spaCy (скачиваем, если нет)
def load_spacy_model():
    try:
        nlp = spacy.load("ru_core_news_sm")
    except OSError:
        print("Модель ru_core_news_sm не найдена. Скачиваем...")
        import subprocess
        subprocess.run(["python", "-m", "spacy", "download", "ru_core_news_sm"])
        nlp = spacy.load("ru_core_news_sm")
    return nlp

nlp = load_spacy_model()

def preprocess(text):
    """Лемматизация, удаление стоп-слов и пунктуации."""
    doc = nlp(text.lower())
    tokens = []
    for token in doc:
        if not token.is_stop and not token.is_punct and not token.is_space:
            tokens.append(token.lemma_)
    return " ".join(tokens)

# ==========================
# 2. ОБУЧЕНИЕ МОДЕЛИ
# ==========================

def train_and_save():
    # Загрузка датасета
    df = create_dataset()
    texts = df["text"].tolist()
    labels = df["intent"].tolist()

    # Предобработка текстов
    print("Выполняется предобработка текстов...")
    processed_texts = [preprocess(t) for t in texts]

    # Векторизация
    print("Векторизация...")
    vectorizer = TfidfVectorizer()
    X = vectorizer.fit_transform(processed_texts)

    # Стратифицированное разбиение на train/test
    X_train, X_test, y_train, y_test = train_test_split(
        X, labels, test_size=0.2, random_state=42, stratify=labels
    )

    # Обучение модели
    print("Обучение логистической регрессии...")
    model = LogisticRegression(max_iter=1000, random_state=42)
    model.fit(X_train, y_train)

    # Оценка качества
    y_pred = model.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)
    print(f"Accuracy: {accuracy:.4f}")
    print("\nClassification Report:")
    print(classification_report(y_test, y_pred, zero_division=0))

    # Сохранение модели и векторизатора
    joblib.dump(model, "model.pkl")
    joblib.dump(vectorizer, "vectorizer.pkl")
    print("Модель и векторизатор сохранены в model.pkl и vectorizer.pkl")

    # Дополнительно: пример предсказания
    test_texts = [
        "привет",
        "погода в москве",
        "сколько времени",
        "сумма 5 10",
        "пока"
    ]
    print("\nПримеры предсказаний:")
    for t in test_texts:
        proc = preprocess(t)
        vec = vectorizer.transform([proc])
        pred = model.predict(vec)[0]
        proba = max(model.predict_proba(vec)[0])
        print(f"'{t}' -> {pred} (уверенность: {proba:.2f})")

if __name__ == "__main__":
    train_and_save()